#!/bin/sh
# Set up the external autostart pieces used by this dwm configuration.
# Safe to re-run. Never overwrite an unrecognised wallpaper/keyboard/display
# setup: ask the user to resolve it instead of guessing at their shell script.
set -eu

home=${HOME:?HOME must be set}
if [ -n "${XDG_DATA_HOME:-}" ]; then
    xdg_dwm=$XDG_DATA_HOME/dwm
else
    xdg_dwm=$home/.local/share/dwm
fi
# Match dwm's runautostart directory selection, including its ~/.dwm fallback.
if [ -d "$xdg_dwm" ]; then
    dir=$xdg_dwm
elif [ -d "$home/.dwm" ]; then
    dir=$home/.dwm
else
    dir=$xdg_dwm
    mkdir -p "$dir"
fi
target=$dir/autostart.sh
tmp=$(mktemp "$dir/.autostart.XXXXXX")
normalized=''
trap 'rm -f "$tmp" ${normalized:+"$normalized"}' EXIT HUP INT TERM

if [ -f "$target" ]; then
    # Delete only the exact old commands supplied by the user, plus our own
    # previously installed block. Keep everything else unchanged. Reject
    # ambiguous commands rather than silently breaking a customised autostart.
    if ! awk '
      BEGIN { inblock = 0; conflict = 0 }
      /^[[:space:]]*# BEGIN DWM MANAGED SETTINGS[[:space:]]*$/ { inblock = 1; next }
      /^[[:space:]]*# END DWM MANAGED SETTINGS[[:space:]]*$/ { if (!inblock) conflict = 1; inblock = 0; next }
      inblock { next }
      /^[[:space:]]*#/ || /^[[:space:]]*$/ { print; next }
      {
        original = $0
        line = $0
        sub(/^[[:space:]]+/, "", line)
        sub(/[[:space:]]*\&[[:space:]]*$/, "", line)
        sub(/[[:space:]]+$/, "", line)
        if (line == "nm-applet") next
        if (line == "xrandr --output eDP-1 --right-of HDMI-1") next
        if (line ~ /(^|\/)refreshmenu([[:space:]]+--apply)$/) next
        if (line == "dwm --apply-display-settings") next
        if (line ~ /^feh[[:space:]]+--bg-fill[[:space:]]+[^[:space:]]*\/Downloads\/wallpaper\/glassmorphsesimjapon[.]png$/) next
        if (line == "setxkbmap -layout us,ir -option \"grp:win_space_toggle\"" ||
            line == "setxkbmap -layout us,ir -option '\''grp:win_space_toggle'\''" ||
            line == "setxkbmap -layout us,ir -option '\'''\''") next
        if (line ~ /(^|[[:space:];])setxkbmap([[:space:]]|$)/ ||
            line ~ /(^|[[:space:];])feh([[:space:]]|$)/ ||
            line ~ /[.]fehbg/ || line ~ /refreshmenu[[:space:]]+--apply/ ||
            line ~ /dwm[[:space:]]+--apply-display-settings/ ||
            line ~ /^xrandr[[:space:]]+.*(--right-of|--mode|--rate)/) {
          print "setup-external: unrecognised conflicting autostart line: " original > "/dev/stderr"
          conflict = 1
        }
        print original
      }
      END {
        if (inblock) { print "setup-external: unterminated managed block" > "/dev/stderr"; conflict = 1 }
        if (conflict) exit 1
      }
    ' "$target" > "$tmp"; then
        echo "Autostart was not changed. Resolve the conflicting lines and rerun." >&2
        exit 1
    fi
else
    printf '#!/bin/sh\n' > "$tmp"
fi

# Normalise only trailing empty lines before the managed block, so re-running
# the script does not accumulate blank lines or create repeated backups.
normalized=$(mktemp "$dir/.autostart.XXXXXX")
awk '{ if ($0 ~ /^[[:space:]]*$/) { blanks = blanks $0 ORS; next }
       printf "%s%s\n", blanks, $0; blanks = "" }' "$tmp" > "$normalized"
mv -f "$normalized" "$tmp"
normalized=''

cat >> "$tmp" <<'BLOCK'

# BEGIN DWM MANAGED SETTINGS
# This block is regenerated by setup-external.sh.
if command -v nm-applet >/dev/null 2>&1; then nm-applet & fi
# Match the user's monitor arrangement only when both outputs are present.
if xrandr --query 2>/dev/null | grep -q '^eDP-1 connected' && \
   xrandr --query 2>/dev/null | grep -q '^HDMI-1 connected'; then
    xrandr --output eDP-1 --right-of HDMI-1
fi
# Apply saved modes after positioning, before restoring the wallpaper.
if command -v dwm >/dev/null 2>&1; then dwm --apply-display-settings; fi
if [ -x "$HOME/.fehbg" ]; then
    "$HOME/.fehbg" &
elif [ -f "$HOME/Downloads/wallpaper/glassmorphsesimjapon.png" ] && command -v feh >/dev/null 2>&1; then
    feh --bg-fill "$HOME/Downloads/wallpaper/glassmorphsesimjapon.png" &
fi
# dwm handles Win+Space; avoid a duplicate XKB group-toggle binding.
if command -v setxkbmap >/dev/null 2>&1; then setxkbmap -layout us,ir -option ''; fi
# END DWM MANAGED SETTINGS
BLOCK

# Refuse to install syntactically invalid scripts. Preserve a timestamped-style
# unique backup and use rename within the same directory for an atomic update.
IFS= read -r firstline < "$tmp" || firstline=''
case "$firstline" in
    '#!/bin/bash'*|'#!/usr/bin/bash'*|'#!/usr/bin/env bash'*) checker=bash ;;
    *) checker=sh ;;
esac
if ! "$checker" -n "$tmp"; then
    echo "setup-external: generated autostart is not valid $checker; original preserved" >&2
    exit 1
fi
if [ -f "$target" ] && cmp -s "$target" "$tmp"; then
    chmod u+x "$target"
    echo "Autostart already configured: $target"
    exit 0
fi
if [ -f "$target" ]; then
    backup=$(mktemp "$dir/autostart.sh.backup.XXXXXX")
    cp -p "$target" "$backup"
    echo "Backup: $backup"
fi
chmod u+x "$tmp"
mv -f "$tmp" "$target"
echo "Updated: $target"
echo 'Saved modes remain in ~/.config/refreshrate.conf (or $XDG_CONFIG_HOME/refreshrate.conf).'
echo 'Wallpaper changes are restored from ~/.fehbg; your fallback is used until that file exists.'
echo 'Install/rebuild the modified dwm separately, then restart the session.'
